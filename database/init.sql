-- =====================================================================
-- Carnet de correspondance numérique : création des tables 
-- Exécuté automatiquement au premier démarrage de Docker.
-- =====================================================================
BEGIN;
 
-- ---------- Structure de l'établissement ----------
CREATE TABLE etablissement (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom           TEXT NOT NULL,
  code          TEXT NOT NULL UNIQUE,
  adresse       TEXT,
  annee_active  TEXT NOT NULL            -- ex. '2026-2027'
);
 
CREATE TABLE utilisateur (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id  INT NOT NULL REFERENCES etablissement(id),
  email             TEXT NOT NULL UNIQUE,
  mot_de_passe_hash TEXT NOT NULL,
  role              TEXT NOT NULL CHECK (role IN ('eleve','parent','enseignant','administration','super_admin')),
  actif             BOOLEAN NOT NULL DEFAULT TRUE,
  double_auth       BOOLEAN NOT NULL DEFAULT FALSE,
  cree_le           TIMESTAMPTZ NOT NULL DEFAULT now()
);
 
CREATE TABLE enseignant (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id  INT NOT NULL REFERENCES etablissement(id),
  utilisateur_id    INT NOT NULL UNIQUE REFERENCES utilisateur(id),
  nom               TEXT NOT NULL,
  prenom            TEXT NOT NULL,
  specialites       TEXT
);
 
CREATE TABLE parent (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id  INT NOT NULL REFERENCES etablissement(id),
  utilisateur_id    INT NOT NULL UNIQUE REFERENCES utilisateur(id),
  nom               TEXT NOT NULL,
  prenom            TEXT NOT NULL,
  telephone         TEXT
);
 
CREATE TABLE classe (
  id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id        INT NOT NULL REFERENCES etablissement(id),
  nom                     TEXT NOT NULL,
  niveau                  TEXT NOT NULL,
  annee_scolaire          TEXT NOT NULL,
  enseignant_principal_id INT REFERENCES enseignant(id),
  UNIQUE (etablissement_id, nom, annee_scolaire)
);
 
CREATE TABLE eleve (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id  INT NOT NULL REFERENCES etablissement(id),
  utilisateur_id    INT UNIQUE REFERENCES utilisateur(id),   -- un élève n'a pas forcément de compte
  classe_id         INT REFERENCES classe(id),
  parent_id         INT REFERENCES parent(id),               -- un parent peut avoir plusieurs enfants, un élève a un seul parent
  lien_parente      TEXT,                                     -- père, mère, tuteur...
  droit_acces          BOOLEAN NOT NULL DEFAULT TRUE,
  droit_justification  BOOLEAN NOT NULL DEFAULT TRUE,
  droit_signature      BOOLEAN NOT NULL DEFAULT TRUE,
  droit_messages       BOOLEAN NOT NULL DEFAULT TRUE,
  nom               TEXT NOT NULL,
  prenom            TEXT NOT NULL,
  date_naissance    DATE,
  matricule         TEXT NOT NULL,
  statut            TEXT NOT NULL DEFAULT 'actif' CHECK (statut IN ('actif','sorti','archive')),
  UNIQUE (etablissement_id, matricule)
);
 
CREATE TABLE matiere (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id  INT NOT NULL REFERENCES etablissement(id),
  libelle           TEXT NOT NULL,
  coefficient       NUMERIC(4,2) NOT NULL DEFAULT 1 CHECK (coefficient > 0),
  niveau            TEXT,
  UNIQUE (etablissement_id, libelle, niveau)
);
 
CREATE TABLE periode (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  etablissement_id  INT NOT NULL REFERENCES etablissement(id),
  nom               TEXT NOT NULL,                           -- ex. 'Trimestre 1'
  debut             DATE NOT NULL,
  fin               DATE NOT NULL,
  verrouillee       BOOLEAN NOT NULL DEFAULT FALSE,
  CHECK (fin > debut)
);
 
CREATE TABLE affectation (
  id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enseignant_id   INT NOT NULL REFERENCES enseignant(id),
  classe_id       INT NOT NULL REFERENCES classe(id),
  matiere_id      INT NOT NULL REFERENCES matiere(id),
  annee_scolaire  TEXT NOT NULL,
  UNIQUE (enseignant_id, classe_id, matiere_id, annee_scolaire)
);
 
-- ---------- Carnet : notes, absences, devoirs, emploi du temps ----------
CREATE TABLE note (
  id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  eleve_id         INT NOT NULL REFERENCES eleve(id),
  matiere_id       INT NOT NULL REFERENCES matiere(id),
  enseignant_id    INT NOT NULL REFERENCES enseignant(id),
  periode_id       INT NOT NULL REFERENCES periode(id),
  intitule         TEXT,                                     -- nom de l'évaluation
  valeur           NUMERIC(5,2),                             -- NULL si absent ou dispensé
  bareme           NUMERIC(5,2) NOT NULL DEFAULT 20 CHECK (bareme > 0),
  coefficient      NUMERIC(4,2) NOT NULL DEFAULT 1 CHECK (coefficient > 0),
  date_evaluation  DATE NOT NULL,
  type             TEXT,
  statut           TEXT NOT NULL DEFAULT 'normale' CHECK (statut IN ('normale','absent','dispense')),
  appreciation     TEXT,
  publiee          BOOLEAN NOT NULL DEFAULT FALSE,
  date_publication DATE,
  supprime_le      TIMESTAMPTZ,                              -- suppression logique
  CHECK (valeur IS NULL OR (valeur >= 0 AND valeur <= bareme))
);
 
CREATE TABLE absence (
  id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  eleve_id             INT NOT NULL REFERENCES eleve(id),
  enseignant_id        INT REFERENCES enseignant(id),        -- déclarant
  date_absence         DATE NOT NULL,
  creneau              TEXT,
  type                 TEXT NOT NULL DEFAULT 'absence' CHECK (type IN ('absence','retard')),
  duree_minutes        INT CHECK (duree_minutes > 0),
  statut_justification TEXT NOT NULL DEFAULT 'non_justifiee'
                       CHECK (statut_justification IN ('non_justifiee','en_attente','justifiee','refusee')),
  motif                TEXT,
  piece_jointe         TEXT,
  supprime_le          TIMESTAMPTZ
);
 
CREATE TABLE devoir (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classe_id      INT NOT NULL REFERENCES classe(id),
  matiere_id     INT NOT NULL REFERENCES matiere(id),
  enseignant_id  INT NOT NULL REFERENCES enseignant(id),
  intitule       TEXT NOT NULL,
  contenu        TEXT NOT NULL DEFAULT '',
  echeance       DATE,
  cree_le        TIMESTAMPTZ NOT NULL DEFAULT now(),
  supprime_le    TIMESTAMPTZ
);
 
CREATE TABLE emploi_du_temps (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  classe_id      INT NOT NULL REFERENCES classe(id),
  matiere_id     INT NOT NULL REFERENCES matiere(id),
  enseignant_id  INT NOT NULL REFERENCES enseignant(id),
  jour           TEXT NOT NULL CHECK (jour IN ('lundi','mardi','mercredi','jeudi','vendredi','samedi','dimanche')),
  heure_debut    TIME NOT NULL,
  heure_fin      TIME NOT NULL,
  salle          TEXT,
  recurrence     TEXT NOT NULL DEFAULT 'hebdomadaire',
  CHECK (heure_fin > heure_debut)
);
 
-- ---------- Communication ----------
CREATE TABLE message (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expediteur_id  INT NOT NULL REFERENCES utilisateur(id),
  objet          TEXT,
  contenu        TEXT NOT NULL,
  date_envoi     TIMESTAMPTZ NOT NULL DEFAULT now(),
  circulaire     BOOLEAN NOT NULL DEFAULT FALSE
);
 
CREATE TABLE message_destinataire (
  message_id      INT NOT NULL REFERENCES message(id) ON DELETE CASCADE,
  utilisateur_id  INT NOT NULL REFERENCES utilisateur(id),
  lu              BOOLEAN NOT NULL DEFAULT FALSE,
  date_lecture    TIMESTAMPTZ,
  PRIMARY KEY (message_id, utilisateur_id)
);
 
-- ---------- Autorisations ----------
CREATE TABLE autorisation (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  createur_id  INT NOT NULL REFERENCES utilisateur(id),
  titre        TEXT NOT NULL,
  description  TEXT,
  date_limite  DATE
);
 
CREATE TABLE autorisation_reponse (
  autorisation_id  INT NOT NULL REFERENCES autorisation(id) ON DELETE CASCADE,
  eleve_id         INT NOT NULL REFERENCES eleve(id),
  parent_id        INT REFERENCES parent(id),                -- renseigné à la signature
  reponse          TEXT NOT NULL DEFAULT 'en_attente' CHECK (reponse IN ('en_attente','accord','refus')),
  date_signature   TIMESTAMPTZ,
  PRIMARY KEY (autorisation_id, eleve_id)
);
 
-- ---------- Vie scolaire ----------
CREATE TABLE incident (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  declarant_id      INT NOT NULL REFERENCES utilisateur(id),
  type              TEXT NOT NULL DEFAULT 'incident' CHECK (type IN ('incident','sanction','recompense')),
  date_incident     DATE NOT NULL,
  description       TEXT NOT NULL,
  gravite           TEXT CHECK (gravite IN ('faible','moyenne','grave')),
  visible_familles  BOOLEAN NOT NULL DEFAULT FALSE,
  supprime_le       TIMESTAMPTZ
);
 
CREATE TABLE incident_eleve (
  incident_id  INT NOT NULL REFERENCES incident(id) ON DELETE CASCADE,
  eleve_id     INT NOT NULL REFERENCES eleve(id),
  PRIMARY KEY (incident_id, eleve_id)
);
 
-- ---------- Index des recherches fréquentes ----------
CREATE INDEX idx_utilisateur_etab   ON utilisateur(etablissement_id);
CREATE INDEX idx_eleve_classe       ON eleve(classe_id);
CREATE INDEX idx_eleve_parent       ON eleve(parent_id);
CREATE INDEX idx_affectation_classe ON affectation(classe_id);
CREATE INDEX idx_note_eleve_periode ON note(eleve_id, periode_id);
CREATE INDEX idx_absence_eleve_date ON absence(eleve_id, date_absence);
CREATE INDEX idx_devoir_classe      ON devoir(classe_id, echeance);
CREATE INDEX idx_edt_classe         ON emploi_du_temps(classe_id);
CREATE INDEX idx_msgdest_user       ON message_destinataire(utilisateur_id, lu);
 
COMMIT;
 
